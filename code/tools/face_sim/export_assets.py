"""Export the firmware's bitmap fonts and icons for the watch face simulator.

Reads code/src/watch_assets.cpp (the generated 1-bit fonts and icons the
firmware draws with) and the two source TTFs, and writes assets.js next to
this script. Run it again after code/tools/generate_ui_assets.py:

    python code/tools/face_sim/export_assets.py

Only the Python standard library is needed.
"""

from __future__ import annotations

import base64
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
CODE = HERE.parents[1]
SOURCE = CODE / "src" / "watch_assets.cpp"
FONT_DIR = CODE / "assets" / "fonts"
OUTPUT = HERE / "assets.js"

ICON_NAMES = [
    "Notifications", "Timer", "Alarms", "Music", "Weather",
    "Sensors", "Activity", "Settings", "Bluetooth", "Battery",
]
TTFS = {
    "regular": "AtkinsonHyperlegibleNext-Regular.ttf",
    "extrabold": "AtkinsonHyperlegibleNext-ExtraBold.ttf",
    # Simulator only: a second typeface to try faces in. The firmware has no
    # bitmaps for it until it is added to generate_ui_assets.py.
    "archivo-regular": "archivo/Archivo-Medium.ttf",
    "archivo-extrabold": "archivo/Archivo-ExtraBold.ttf",
}


def array_body(text: str, name: str) -> str:
    match = re.search(r"\b%s\[\] = \{(.*?)\n\};" % re.escape(name), text, re.S)
    if match is None:
        raise SystemExit(f"{name} not found in {SOURCE}")
    return match.group(1)


def byte_array(text: str, name: str) -> str:
    values = [int(v, 16) for v in re.findall(r"0x([0-9A-Fa-f]{2})", array_body(text, name))]
    return base64.b64encode(bytes(values)).decode("ascii")


def struct_array(text: str, name: str) -> list[list[int]]:
    return [
        [int(v) for v in row.split(",")]
        for row in re.findall(r"\{([-\d, ]+)\}", array_body(text, name))
    ]


def main() -> None:
    text = SOURCE.read_text(encoding="utf8")
    fonts = {}
    for match in re.finditer(
        r"const BitmapFont (\w+) = \{\w+, \w+, (\d+), (\d+), (\d+), (\d+), (\d+)\};", text
    ):
        name, first, last, size, ascent, descent = match.groups()
        fonts[name] = {
            "first": int(first),
            "last": int(last),
            "size": int(size),
            "ascent": int(ascent),
            "descent": int(descent),
            # [bitmap_offset, width, height, x_offset, y_offset, x_advance]
            "glyphs": struct_array(text, f"{name}_GLYPHS"),
            "bitmap": byte_array(text, f"{name}_BITMAP"),
        }
    if not fonts:
        raise SystemExit("no fonts found")
    icons = {
        "names": ICON_NAMES,
        # [bitmap_offset, width, height] per icon
        "16": struct_array(text, "ICONS_16"),
        "28": struct_array(text, "ICONS_28"),
        "bitmap": byte_array(text, "ICON_BITMAP"),
    }
    if len(icons["16"]) != len(ICON_NAMES):
        raise SystemExit("icon list in this script is out of date")
    ttf = {
        key: base64.b64encode((FONT_DIR / filename).read_bytes()).decode("ascii")
        for key, filename in TTFS.items()
    }
    OUTPUT.write_text(
        "// Generated by export_assets.py from code/src/watch_assets.cpp. Do not edit.\n"
        "window.WATCH_ASSETS = "
        + json.dumps({"fonts": fonts, "icons": icons, "ttf": ttf}, separators=(",", ":"))
        + ";\n",
        encoding="utf8",
    )
    print(f"wrote {OUTPUT} ({OUTPUT.stat().st_size // 1024} KiB): fonts {', '.join(fonts)}")


if __name__ == "__main__":
    main()
